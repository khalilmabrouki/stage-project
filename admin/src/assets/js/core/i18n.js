function initI18n() {
  const savedLang = localStorage.getItem('tarento_lang') || 'en';
  
  // Apply language on load
  applyLanguage(savedLang);

  // Set up event listeners for language dropdown
  const langSwitches = document.querySelectorAll('.language-switch');
  
  langSwitches.forEach(switchEl => {
    switchEl.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = e.currentTarget.getAttribute('data-lang');
      
      // Update active state in dropdown
      langSwitches.forEach(el => {
        el.classList.remove('active', 'bg-primary-subtle', 'text-primary', 'fw-medium');
      });
      e.currentTarget.classList.add('active', 'bg-primary-subtle', 'text-primary', 'fw-medium');
      
      // Update the main dropdown trigger button image
      const triggerImg = document.querySelector('.dropdown [data-bs-toggle="dropdown"][title="Language"] img');
      const targetImg = e.currentTarget.querySelector('img');
      if (triggerImg && targetImg) {
        triggerImg.src = targetImg.src;
        triggerImg.alt = targetImg.alt;
      }

      applyLanguage(lang);
      localStorage.setItem('tarento_lang', lang);
    });
  });
}

function applyLanguage(lang) {
  const dict = translations[lang] || translations['en'];
  
  // Find all elements with data-i18n attribute
  const elements = document.querySelectorAll('[data-i18n]');
  
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      // If element has nested icon, only replace the text node
      // Or simply replace the text content, wait, if it's a sub-link it might have an icon.
      // Easiest is to set innerText, but wait, some elements like 'Level 1.2' have a chevron-down icon inside.
      // Let's iterate child nodes and replace the first text node we find that is not empty.
      
      let textUpdated = false;
      for (const node of el.childNodes) {
        if (node.nodeType === Node.TEXT_NODE && node.nodeValue.trim() !== '') {
          node.nodeValue = ' ' + dict[key] + ' ';
          textUpdated = true;
          break;
        }
      }
      // Fallback if no text node found
      if (!textUpdated) {
        el.textContent = dict[key];
      }
    }
  });
}
